// Firebase messaging service worker for background notifications
// Place this file in your public directory

importScripts('https://www.gstatic.com/firebasejs/9.0.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/9.0.0/firebase-messaging-compat.js');

// Initialize Firebase in the service worker
firebase.initializeApp({
  apiKey: "your-api-key",
  authDomain: "your-project.firebaseapp.com",
  projectId: "your-project-id",
  storageBucket: "your-project.appspot.com",
  messagingSenderId: "your-sender-id",
  appId: "your-app-id"
});

const messaging = firebase.messaging();

// Handle background messages
messaging.onBackgroundMessage((payload) => {
  console.log('Background message received:', payload);
  
  const notificationTitle = payload.notification?.title || 'Disaster Alert';
  const notificationOptions = {
    body: payload.notification?.body || 'Emergency notification received',
    icon: payload.notification?.icon || '/icon-192x192.png',
    badge: '/badge-icon.png',
    tag: payload.data?.type || 'disaster-alert',
    requireInteraction: payload.data?.severity === '3', // Keep urgent alerts visible
    actions: [
      {
        action: 'view',
        title: 'View Details'
      },
      {
        action: 'dismiss',
        title: 'Dismiss'
      }
    ],
    data: payload.data
  };

  self.registration.showNotification(notificationTitle, notificationOptions);
});

// Handle notification clicks
self.addEventListener('notificationclick', (event) => {
  console.log('Notification clicked:', event);
  
  event.notification.close();
  
  if (event.action === 'view') {
    // Open the app to show disaster details
    event.waitUntil(
      clients.openWindow('/?notification=' + event.notification.tag)
    );
  }
});